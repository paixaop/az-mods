"""Freeze the native HMM's normalized transition matrix with its original byte check.

This is a mathematical table, generated from the port's public formula. Builds use
the checked-in result so platform libm implementations cannot change its last bits.
"""
from pathlib import Path
import hashlib
import math
import struct

intervals = list(range(33, 87))
kernel = []
for source in intervals:
    row = [math.exp(-100.0 * abs(target / source - 1)) for target in intervals]
    row = [value if value > 2.0 ** -52 else 0.0 for value in row]
    lanes = [0.0] * 8
    stop = len(row) // 8 * 8
    for i in range(stop):
        lanes[i % 8] += row[i]
    total = ((lanes[0] + lanes[1]) + (lanes[2] + lanes[3])) + ((lanes[4] + lanes[5]) + (lanes[6] + lanes[7]))
    for value in row[stop:]:
        total += value
    kernel.append([value / total for value in row])

probabilities = []
for beat in range(4):
    for index, interval in enumerate(intervals):
        probabilities.extend(kernel[source][index] for source in range(54) if kernel[source][index])
        probabilities.extend([1.0] * (interval - 1))
packed = struct.pack("<" + "d" * len(probabilities), *probabilities)
expected = "8e9c5fda054ed7de14fa5d5a0991029933987a0649a31272fbfcf630faa75111"
if hashlib.sha256(packed).hexdigest() != expected:
    raise SystemExit("This host's libm differs from the frozen model; preserve the checked-in kernel.")
out = Path(__file__).resolve().parents[1] / "worker/Sources/PortableDSP/hmm-kernel.h"
out.write_text("/* SPDX-License-Identifier: GPL-3.0-only */\n"
               "/* Generated by tools/generate-hmm-kernel.py; canonical model SHA-256 verified. */\n"
               "static const double ta_native_hmm_kernel[54][54] = {\n" +
               "\n".join("    {" + ", ".join(value.hex() for value in row) + "}," for row in kernel) + "\n};\n")
print("Verified and generated canonical HMM transition kernel")
